// ── Runtime ───────────────────────────────────────────────────────────────────
let _lang = localStorage.getItem('lang') || 'es';

/** Translate a key. Falls back to Spanish, then the key itself. */
function t(key) {
  return (I18N[_lang] && I18N[_lang][key] !== undefined)
    ? I18N[_lang][key]
    : (I18N.es[key] !== undefined ? I18N.es[key] : key);
}

/** Switch language, persist, and re-apply to DOM. */
function setLang(lang) {
  if (!I18N[lang]) return;
  _lang = lang;
  localStorage.setItem('lang', lang);
  applyI18n();
}

/** Update every element with a data-i18n* attribute, then re-render if data loaded. */
function applyI18n() {
  document.documentElement.lang = _lang === 'zh' ? 'zh-CN' : _lang;
  document.title = t('pageTitle');

  // textContent replacements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // innerHTML replacements (for nodes containing <strong> etc.)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  // placeholder attributes
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  // title attributes
  document.querySelectorAll('[data-i18n-ttl]').forEach(el => {
    el.title = t(el.dataset.i18nTtl);
  });

  // Select options that are static in HTML (dynamic ones are handled in render fns)
  _updateSelectOptions();

  // Highlight active lang button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === _lang);
  });

  // Re-render charts/tables with new language if data is loaded
  if (typeof D !== 'undefined' && D && typeof render === 'function') {
    render();
  }
}

